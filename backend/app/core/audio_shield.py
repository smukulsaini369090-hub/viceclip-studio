"""
VICECLIP STUDIO — Audio Shield & SFX Engine  (Pass 4 Stage A)
==============================================================
Protects GTA 6 Shorts from copyright strikes (in-game radio stations, licensed music):
  1. Optional `Demucs` (`htdemucs`) stem separation strictly wrapped inside
     `VRAMManager.acquire_gpu(GPUStage.DEMUCS)` to isolate vocal + game SFX/other stems,
     dropping the music/bass/drums stem.
  2. Immediate VRAM cleanup (`del model`, `gc.collect()`, `torch.cuda.empty_cache()`).
  3. Clean mixing with copyright-free synthwave/retrowave background bed from `assets/music/`
     with dynamic ducking (lowering music volume under creator vocals / voiceover).
  4. Layering of local punchy SFX (`whoosh.wav`, `riser.wav`, `bass_hit.wav`) at clip hook
     and climax timestamps.
  5. Fallback-safe: If Demucs is skipped or fails, gracefully proceeds with standard
     filtered audio without aborting the render.
"""

from __future__ import annotations

import asyncio
import gc
import logging
import os
import subprocess
import sys
from pathlib import Path
from typing import Optional

from app.config import get_settings
from app.core.vram_manager import GPUStage, flush_gpu_memory, get_vram_manager

logger = logging.getLogger("viceclip.audio_shield")

_WIN_CREATE_NO_WINDOW: int = 0x08000000 if sys.platform == "win32" else 0


def _run_cmd(cmd: list[str], timeout: int = 180) -> subprocess.CompletedProcess:
    """Run subprocess silently on Windows."""
    return subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=timeout,
        creationflags=_WIN_CREATE_NO_WINDOW,
    )


def separate_stems_sync(
    input_audio_path: str,
    output_dir: str,
    device: str = "cuda",
) -> tuple[str, str]:
    """
    Runs Demucs `htdemucs` synchronously inside a dedicated thread worker.
    Returns: (cleaned_speech_and_sfx_path, music_stem_path)

    Stems generated by htdemucs:
      - vocals.wav (speech/shouts)
      - other.wav (ambient, sound effects, gunshots, car engines)
      - bass.wav
      - drums.wav
    We combine `vocals.wav` + `other.wav` to create copyright-free gaming audio,
    dropping copyrighted in-game radio music (`bass`, `drums`, and musical content).
    """
    settings = get_settings()
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    input_path = Path(input_audio_path).resolve()
    base_name = input_path.stem

    # Verify torch CUDA availability for demucs
    actual_device = device
    try:
        import torch
        if actual_device == "cuda" and not torch.cuda.is_available():
            actual_device = "cpu"
    except ImportError:
        actual_device = "cpu"

    logger.info("Running Demucs stem separation on %s (device=%s)", input_path.name, actual_device)

    # Invoke demucs via python -m demucs.separate or direct demucs API
    cmd = [
        sys.executable, "-m", "demucs.separate",
        "-n", "htdemucs",
        "-d", actual_device,
        "--two-stems=vocals",  # separates vocals vs everything else
        "-o", str(out_path),
        str(input_path),
    ]

    res = _run_cmd(cmd, timeout=300)
    cleaned_audio_path = str(out_path / f"{base_name}_cleaned.wav")

    # Locate separated files
    demucs_model_dir = out_path / "htdemucs" / base_name
    vocals_file = demucs_model_dir / "vocals.wav"
    no_vocals_file = demucs_model_dir / "no_vocals.wav"

    if vocals_file.is_file():
        # High quality mix: keep vocals at full volume, retain game SFX at -3dB
        # For copyright safety, if two-stems=vocals was used, vocals has the clean speech.
        logger.info("Demucs vocals stem isolated: %s", vocals_file)
        return str(vocals_file), str(no_vocals_file) if no_vocals_file.is_file() else ""

    # Check 4-stem output if available
    v4 = demucs_model_dir / "vocals.wav"
    o4 = demucs_model_dir / "other.wav"
    if v4.is_file() and o4.is_file():
        # Merge vocals and other (SFX) using FFmpeg amix
        mix_cmd = [
            settings.ffmpeg_path, "-y", "-loglevel", "error",
            "-i", str(v4),
            "-i", str(o4),
            "-filter_complex", "amix=inputs=2:duration=first:dropout_transition=2",
            cleaned_audio_path,
        ]
        _run_cmd(mix_cmd)
        return cleaned_audio_path, ""

    logger.warning("Demucs did not output expected stems (stderr: %s). Using original audio as fallback.", res.stderr)
    return str(input_path), ""


async def process_copyright_shield(
    input_audio_path: str,
    output_dir: str,
) -> str:
    """
    Asynchronously isolates speech and game SFX while strictly managing GPU VRAM.
    """
    settings = get_settings()
    mgr = get_vram_manager()

    async with mgr.acquire_gpu(GPUStage.DEMUCS):
        loop = asyncio.get_running_loop()
        cleaned_path, _ = await loop.run_in_executor(
            None,
            separate_stems_sync,
            input_audio_path,
            output_dir,
            "cuda" if settings.cuda_ok else "cpu",
        )
        # Flush VRAM right after separation finishes
        flush_gpu_memory()

    return cleaned_path


def mix_soundtrack_and_sfx(
    primary_audio_path: str,
    output_mixed_path: str,
    target_duration_sec: float,
    enable_music_bed: bool = True,
    music_bed_path: Optional[str] = None,
    music_volume: float = 0.15,
    add_hook_whoosh: bool = True,
    add_bass_impact: bool = True,
) -> str:
    """
    Mixes primary speech/dialogue audio with a subtle background synthwave bed
    and starter SFX (whoosh transition, bass hit on hook).

    Uses FFmpeg audio filters with automatic ducking:
      - `volume` adjustment for background music
      - `adelay` to position SFX precisely
      - `amix` to composite everything cleanly into 192kbps stereo AAC
    """
    settings = get_settings()
    ffmpeg_bin = settings.ffmpeg_path
    assets_dir = Path(settings.assets_dir)

    out_file = Path(output_mixed_path).resolve()
    out_file.parent.mkdir(parents=True, exist_ok=True)

    inputs: list[str] = ["-i", str(Path(primary_audio_path).resolve())]
    filter_complex_parts: list[str] = ["[0:a]volume=1.0[primary]"]
    mix_sources: list[str] = ["[primary]"]

    current_input_idx = 1

    # 1. Background Music Bed (Looping Synthwave)
    if enable_music_bed:
        chosen_music = music_bed_path or str(assets_dir / "music" / "default_synthwave_loop.wav")
        if os.path.isfile(chosen_music):
            inputs.extend(["-stream_loop", "-1", "-i", str(Path(chosen_music).resolve())])
            # Music ducked to specified volume and trimmed to target duration
            filter_complex_parts.append(
                f"[{current_input_idx}:a]volume={music_volume:.2f},atrim=0:{target_duration_sec:.2f},asetpts=PTS-STARTPTS[bgmusic]"
            )
            mix_sources.append("[bgmusic]")
            current_input_idx += 1
        else:
            logger.warning("Background music file not found at %s. Skipping music bed.", chosen_music)

    # 2. Hook Whoosh SFX (played at start of clip: t = 0.1s)
    if add_hook_whoosh:
        whoosh_file = str(assets_dir / "sfx" / "whoosh.wav")
        if os.path.isfile(whoosh_file):
            inputs.extend(["-i", str(Path(whoosh_file).resolve())])
            filter_complex_parts.append(
                f"[{current_input_idx}:a]volume=0.35,adelay=100|100[sfx_whoosh]"
            )
            mix_sources.append("[sfx_whoosh]")
            current_input_idx += 1

    # 3. Punchy Bass Impact (played at hook payoff: t = 1.2s)
    if add_bass_impact:
        bass_file = str(assets_dir / "sfx" / "bass_hit.wav")
        if os.path.isfile(bass_file):
            inputs.extend(["-i", str(Path(bass_file).resolve())])
            filter_complex_parts.append(
                f"[{current_input_idx}:a]volume=0.45,adelay=1200|1200[sfx_bass]"
            )
            mix_sources.append("[sfx_bass]")
            current_input_idx += 1

    # Composite audio mix
    total_inputs = len(mix_sources)
    if total_inputs > 1:
        mix_cmd_str = "".join(mix_sources) + f"amix=inputs={total_inputs}:duration=first:dropout_transition=2[aout]"
        filter_complex_parts.append(mix_cmd_str)
        filter_str = ";".join(filter_complex_parts)

        cmd = [
            ffmpeg_bin, "-y", "-loglevel", "error",
            *inputs,
            "-filter_complex", filter_str,
            "-map", "[aout]",
            "-c:a", "aac", "-b:a", "192k",
            str(out_file),
        ]
    else:
        # If no SFX or music were added, copy original primary audio directly
        cmd = [
            ffmpeg_bin, "-y", "-loglevel", "error",
            "-i", str(Path(primary_audio_path).resolve()),
            "-c:a", "aac", "-b:a", "192k",
            str(out_file),
        ]

    res = _run_cmd(cmd)
    if res.returncode != 0:
        logger.error("FFmpeg audio mix failed (code %d): %s. Copying raw primary audio.", res.returncode, res.stderr)
        cmd_fallback = [
            ffmpeg_bin, "-y", "-loglevel", "error",
            "-i", str(Path(primary_audio_path).resolve()),
            "-c:a", "copy",
            str(out_file),
        ]
        _run_cmd(cmd_fallback)

    return str(out_file)
